# -*- coding: utf-8 -*-
"""Phase 9 — assemble experiments/RESULTS.md from all result artifacts, and refresh
the modeling section of reports/PROJECT_REPORT.md with the new champion numbers.

Reads only the CSV/JSON/PNG the pipeline produced; safe to re-run. Missing artifacts
are skipped with a note so a partial run still yields a readable report.
"""
from __future__ import annotations
import os, json
import pandas as pd

from common import CFG, rp, git_hash

RES = CFG["paths"]["results_dir"]
FIG = "results/figures"   # relative path used inside experiments/RESULTS.md


def _exists(name):
    return os.path.exists(rp(RES, name))


def _read_json(name):
    p = rp(RES, name)
    return json.load(open(p, encoding="utf-8")) if os.path.exists(p) else None


def _md_table(df, cols=None, float_fmt=None):
    if cols:
        df = df[[c for c in cols if c in df.columns]]
    df = df.copy()
    if float_fmt:
        for c in df.columns:
            if pd.api.types.is_float_dtype(df[c]):
                df[c] = df[c].map(lambda v: float_fmt.format(v) if pd.notna(v) else "")
    head = "| " + " | ".join(str(c) for c in df.columns) + " |"
    sep = "| " + " | ".join("---" for _ in df.columns) + " |"
    body = ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, sep] + body)


def build():
    L = []
    A = L.append
    A("# Experiment Results — Codeforces Rating & Tag Prediction\n")
    A(f"*Generated by `experiments/src/run_experiment.py` (seed {CFG['seed']}, git `{git_hash()}`). "
      "Non-transformer models only.*\n")
    A("**Protocol:** locked 80/20 hold-out via `GroupShuffleSplit` on `cv_group`; model "
      "selection by `GroupKFold(5)` inside train; every vectorizer/scaler/embedding fit on "
      "train folds only. Leaderboards show CV mean±std over the 5 shared folds; the champion "
      "is then run once on the locked test.\n")

    # ---------------- rating ----------------
    A("\n## 1. Rating regression (§4)\n")
    if _exists("leaderboard_rating.csv"):
        lb = pd.read_csv(rp(RES, "leaderboard_rating.csv"))
        cols = ["model", "family", "feature_set", "MAE_mean", "MAE_std", "RMSE_mean",
                "R2_mean", "Spearman_mean", "acc_100_mean", "acc_200_mean", "MAE_locked", "R2_locked"]
        A("CV mean±std (ranked by CV MAE) with locked-test MAE/R²:\n")
        A(_md_table(lb, cols, "{:.3f}"))
        champ = lb.iloc[0]
        A(f"\n**Champion:** `{champ['model']}` — locked-test MAE **{champ['MAE_locked']}**, "
          f"R² **{champ['R2_locked']}** (baseline mean-MAE ≈ 609).\n")

    # ---------------- tags ----------------
    A("\n## 2. Tag multi-label classification (§5)\n")
    if _exists("leaderboard_tags.csv"):
        lb = pd.read_csv(rp(RES, "leaderboard_tags.csv"))
        cols = ["model", "family", "feature_set", "f1_micro_mean", "f1_macro_mean",
                "precision_micro_mean", "recall_micro_mean", "hamming_loss_mean",
                "jaccard_samples_mean", "f1_micro_locked", "f1_macro_locked"]
        A("CV mean±std (ranked by CV micro-F1) with locked-test F1:\n")
        A(_md_table(lb, cols, "{:.4f}"))
        champ = lb.iloc[0]
        A(f"\n**Champion:** `{champ['model']}` — locked-test micro-F1 **{champ['f1_micro_locked']}**, "
          f"macro-F1 **{champ['f1_macro_locked']}**.\n")

    # ---------------- significance ----------------
    A("\n## 3. Statistical significance (§6.3)\n")
    sig = _read_json("significance_summary.json")
    if sig:
        for task in ("rating", "tags"):
            s = sig[task]["significance"]
            fr = s.get("friedman", {})
            w = s.get("wilcoxon_top2", {})
            A(f"- **{task}** — Friedman χ²={fr.get('stat', float('nan')):.2f} (p={fr.get('p', float('nan')):.3g}); "
              f"paired Wilcoxon top-2 `{w.get('a')}` vs `{w.get('b')}` p={w.get('p', float('nan')):.3g}. "
              f"CD diagram: `{FIG}/cd_{task}.png`.")
            dis = sig[task]["disagreements"]["disagreements"]
            if dis:
                A(f"  - ranking disagreements: " +
                  "; ".join(f"{d['metric']} tops with `{d['this_top']}`" for d in dis))
        A("\n*(5 folds → low-power omnibus tests; read alongside the effect sizes above.)*\n")

    # ---------------- thresholds + ordinal ----------------
    A("\n## 4. Imbalance, thresholds & ordinal framing (§5.4 / §4.4)\n")
    th = _read_json("phase5_tags_thresholds.json")
    if th:
        b, t = th["threshold_0.5"], th["threshold_tuned"]
        A(f"- **Per-label threshold tuning** ({th['champion']}): macro-F1 "
          f"{b['f1_macro']} → **{t['f1_macro']}** (lift {th['macro_f1_lift']}); "
          f"micro-F1 {b['f1_micro']} → {t['f1_micro']}; recall_micro {b['recall_micro']} → {t['recall_micro']}.")
        fl = th["macro_f1_floor15"]
        A(f"- **Rare-tag floor** (≥{CFG['tags']['rare_floor']} train ex., {fl['n_tags']} tags): "
          f"macro-F1 base {fl['base']} → tuned {fl['tuned']} (vs all-38 base {th['macro_f1_all38']['base']}).")
        if "special_tag" in th:
            sp = th["special_tag"]
            A(f"- **`{sp['tag']}`** (meta-tag, n={sp['train_support']}): F1 {sp['f1_base']} → {sp['f1_tuned']}.")
        it = th.get("iterative_stratification_sanity", {})
        if "f1_micro" in it:
            A(f"- **Iterative-stratification sanity** (row-level, non-grouped): micro-F1 {it['f1_micro']}, "
              f"macro-F1 {it['f1_macro']} — {it['note']}.")
    od = _read_json("phase5_ordinal_rating.json")
    if od:
        oc, rc = od["ordinal_classifier"], od["regression_champion"]
        A(f"- **Ordinal framing** ({od['n_bands']} bands): direct classifier exact-band "
          f"{oc['exact_band_acc']} / within-one {oc['within_one_band_acc']}; regression champion "
          f"`{rc['model']}` bucketed exact-band {rc['exact_band_acc']} / within-one {rc['within_one_band_acc']}.")

    # ---------------- per-tag ----------------
    A("\n## 5. Per-tag F1 (champion, locked test)\n")
    if _exists("per_tag_f1.csv"):
        pt = pd.read_csv(rp(RES, "per_tag_f1.csv")).sort_values("f1", ascending=False)
        top = pt.head(10); bot = pt[pt["f1"] == 0.0]
        A("Strongest tags:\n"); A(_md_table(top, ["tag", "f1", "precision", "recall", "support"], "{:.3f}"))
        A(f"\nUnrecovered (F1=0): {', '.join('`'+t+'`' for t in bot['tag'])} — the long-tail ceiling.\n")
        A(f"\nFull per-tag table: `results/per_tag_f1.csv`. Figure: `{FIG}/tags_per_tag_f1.png`.\n")

    # ---------------- ablations ----------------
    A("\n## 6. Ablations (§8)\n")
    for fn, title, cols in [
        ("ablation_feature_family.csv", "Feature-family lift", None),
        ("ablation_tfidf.csv", "TF-IDF variants", None),
        ("ablation_w2v.csv", "Word2Vec params (rating, fold-0 probe)", None),
        ("ablation_tag_strategy.csv", "Tag strategy", None)]:
        if _exists(fn):
            A(f"\n**{title}** (`results/{fn}`):\n")
            A(_md_table(pd.read_csv(rp(RES, fn)), cols, "{:.4f}"))

    # ---------------- figures + repro ----------------
    A("\n## 7. Figures & reproducibility\n")
    A("Figures in `results/figures/`: `cd_rating.png`, `cd_tags.png`, `rating_residuals.png`, "
      "`rating_calibration.png`, `rating_stats_importance.png`, `tags_per_tag_f1.png`.\n")
    A("Reproduce all of the above with `python experiments/src/run_experiment.py`. "
      "Library versions in `results/versions.txt`. Interpretability CSVs: "
      "`rating_top_tokens.csv`, `tags_top_tokens_per_tag.csv`, `tags_confusion_pairs.csv`, "
      "`rating_worst_predictions.csv`.\n")

    out = rp("experiments", "RESULTS.md")
    open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(f"wrote {out}")
    _refresh_project_report()


def _refresh_project_report():
    """Update the headline numbers in reports/PROJECT_REPORT.md §10 to the new run,
    with a pointer to experiments/RESULTS.md. Only touches a clearly-marked block."""
    path = rp("reports", "PROJECT_REPORT.md")
    if not os.path.exists(path):
        return
    if not (_exists("leaderboard_rating.csv") and _exists("leaderboard_tags.csv")):
        return
    lbr = pd.read_csv(rp(RES, "leaderboard_rating.csv")).iloc[0]
    lbt = pd.read_csv(rp(RES, "leaderboard_tags.csv")).iloc[0]
    marker = "<!-- EXPERIMENTS-HARNESS-SUMMARY -->"
    block = (f"{marker}\n"
             f"### 10.4 Extended harness (experiments/, seed 42)\n\n"
             f"A broader roster on identical `GroupKFold(5)` folds + a locked test lives in "
             f"`experiments/` (see `experiments/RESULTS.md`). Champions:\n\n"
             f"- **Rating:** `{lbr['model']}` — locked MAE **{lbr['MAE_locked']}**, R² **{lbr['R2_locked']}** "
             f"(CV MAE {lbr['MAE_mean']}±{lbr['MAE_std']}).\n"
             f"- **Tags:** `{lbt['model']}` — locked micro-F1 **{lbt['f1_micro_locked']}**, "
             f"macro-F1 **{lbt['f1_macro_locked']}** (CV micro-F1 {lbt['f1_micro_mean']}±{lbt['f1_micro_std']}).\n\n"
             f"Adds significance tests (Friedman/Nemenyi + CD diagrams), per-label threshold tuning, "
             f"an ordinal-rating study, feature-family/TF-IDF/Word2Vec ablations, and error analysis. "
             f"{marker}")
    txt = open(path, encoding="utf-8").read()
    if marker in txt:
        import re
        txt = re.sub(re.escape(marker) + r".*?" + re.escape(marker), block, txt, flags=re.S)
    else:
        txt = txt.rstrip() + "\n\n---\n\n" + block + "\n"
    open(path, "w", encoding="utf-8").write(txt)
    print(f"refreshed {path}")


if __name__ == "__main__":
    build()
